import java.util.Scanner;

public class consoleIO {
	Scanner s;
	pushdown p;
	boolean b;
	
	public consoleIO(pushdown p) {
		s = new Scanner(System.in);
		this.p = p;
		b = true;
	}
	
	
	public void input() {
		
		System.out.println("Please enter a number 1-11");
		System.out.println("1. Test Input");
		System.out.println("2. Add new state");
		System.out.println("3. Add new transition");
		System.out.println("4. Remove state");
		System.out.println("5. Remove transition");
		System.out.println("6. Display Automaton"); //add delta
		System.out.println("7. Add to stack alphabet");
		System.out.println("8. Remove from stack alphabet");
		System.out.println("9. Add to input alphabet");
		System.out.println("10. Remove from input alphabet");
		System.out.println("11. Make state accepting");
		System.out.println("12. Remove state from accepting");
		System.out.println("13. Show instructions");
		System.out.println("14. Exit");
		
		go();	
	}
	
	private void go() {
		System.out.println("Enter an instruction: ");
		
		int n = s.nextInt();
		
		if(n == 1) {
			System.out.println("Enter the input string: ");
			boolean b = p.inputOld(s.next());
			if(b) {System.out.println("This input belongs to the languge generated by the automaton");}
			else {System.out.println("This input does not belong to the languge generated by the automaton");}
		}
		if(n == 2) {
			boolean a;
			System.out.println("Enter state name:");
			String name = s.next();
			
			if(p.getStates().length == 0) {a = true;}
			else {a = false;}
			p.addState(new state(name, a, false));
			
		}
		if(n == 3) {
			System.out.println("Enter start state name");
			String a = s.next();
			System.out.println("Enter end state name");
			String b = s.next();
			System.out.println("Enter symbol for transition");
			String c = s.next();
			System.out.println("Enter start stack state");
			String d = s.next();
			System.out.println("Enter end stack state");
			String e = s.next();
			System.out.println("If there is another element of the end stack state enter it now, if not then enter a full stop");
			String f = s.next();
			
			String[] t = {e,f}; 
					
			if(f.equals(".")) {
				String[] r = {e};
				p.addTransition(a,c,d,b,r);
			}
			else {
				p.addTransition(a,c,d,b,t);
			}
			
		}
		if(n == 4) {
			System.out.println("Enter state name:");
			p.removeState(s.next());
		}
		if(n == 5) {
			System.out.println("Enter start state name");
			String a = s.next();
			System.out.println("Enter symbol for transition");
			String b = s.next();
			System.out.println("Enter start stack symbol");
			String c = s.next();
			p.removeTransition(a,b,c);
		}
		if(n == 6) {
			p.printStates();
			p.printInputAlphabet();
			p.printStackAlphabet();
			System.out.println("Start state = " + p.getStartState().getName());
			System.out.println("Start stack symbol = " + p.getStartStackSymbol().getValue());
			p.printAcceptingStates();
			p.printTranstions();
		}
		if(n == 7) {
			System.out.println("Enter new alphabet character: ");			
			p.addToStackAlphabet(s.next());
		}
		if(n == 8) {
			System.out.println("Enter character:");
			p.removeFromStackAlphabet(s.next());
		}
		if(n == 9) {
			System.out.println("Enter new alphabet character: ");			
			p.addToInputAlphabet(s.next());
		}
		if(n == 10) {
			System.out.println("Enter character:");
			p.removeFromInputAlphabet(s.next());
		}
		if(n == 11) {
			System.out.println("Enter state name:");
			p.addAccepting(s.next());
		}
		if(n == 12) {
			System.out.println("Enter state name:");
			p.removeAccepting(s.next());
		}
		if(n == 13) {
			System.out.println("Please enter a number 1-11");
			System.out.println("1. Test Input");
			System.out.println("2. Add new state");
			System.out.println("3. Add new transition");
			System.out.println("4. Remove state");
			System.out.println("5. Remove transition");
			System.out.println("6. Display Automaton");
			System.out.println("7. Add to stack alphabet");
			System.out.println("8. Remove from stack alphabet");
			System.out.println("9. Add to input alphabet");
			System.out.println("10. Remove from input alphabet");
			System.out.println("11. Make state accepting");
			System.out.println("12. Remove state from accepting");
			System.out.println("13. Show instructions");
			System.out.println("14. Exit");
		}
		if(n == 14) {
			b = false;
			return;
		}
		
		go();
		
	}
	
}
